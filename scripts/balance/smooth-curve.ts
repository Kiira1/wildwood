import { readFileSync } from 'node:fs';
import { CAMPAIGN_MAPS } from '../../shared/campaign-registry';
import { CURVE_STEPS } from '../../shared/curve-steps';
import { enemyDefeatDefinition } from '../../shared/enemy-defeats';
import { resolveMapBalance } from '../../shared/map-balance';

/**
 * Builds shared/smooth-curve.ts: every campaign map's enemies and boss on CURVE_STEPS. Each role (regular or elite,
 * by what it pays) is a fixed multiple of its map's damage camp, its average over the source revision's maps 2-15,
 * and the damage camp grows by the steps from Tutorial Forest's: every role grows by the same step every map. The
 * Forest's Spitter keeps its own numbers. Each boss is a fixed multiple of its damage camp's health and keeps its
 * attacks' size against the camp's hit. scripts/generated-balance-files.test.ts regenerates it and fails on any drift.
 */
export const SMOOTH_CURVE_SOURCE = { revision: 79, fixture: 'tests/fixtures/balance-revision-79.json' } as const;
export const SMOOTH_CURVE_FILE = 'shared/smooth-curve.ts';

type Stats = { hp: number; damage: number; reward: number };
const round = (n: number) => Number(n.toPrecision(6));
const paysRating = (type: string) => type === 'speed' || type === 'crit';
const roleOf = (row: { elite?: boolean; reward: { type: string } }) =>
  `${row.elite ? 'elite' : 'regular'}:${paysRating(row.reward.type) ? 'damage' : row.reward.type}`;
const geomean = (values: number[]) => Math.exp(values.reduce((sum, v) => sum + Math.log(v), 0) / values.length);

export function buildSmoothCurve(root = '.') {
  const settings = JSON.parse(readFileSync(`${root}/${SMOOTH_CURVE_SOURCE.fixture}`, 'utf8'));
  const snapshots = CAMPAIGN_MAPS.map(map => resolveMapBalance(map.id, settings, SMOOTH_CURVE_SOURCE.revision, 2));
  // Each role on a map, weighted by how many of each enemy it spawns. Rewards only from enemies paying that stat.
  const roles = CAMPAIGN_MAPS.map((map, index) => {
    const sums: Record<string, { weight: number; hp: number; damage: number; rewardWeight: number; reward: number }> = {};
    for (const [kind, row] of Object.entries(snapshots[index].enemies)) {
      const count = enemyDefeatDefinition(map.id, kind)?.population ?? 0;
      const sum = sums[roleOf(row)] ??= { weight: 0, hp: 0, damage: 0, rewardWeight: 0, reward: 0 };
      sum.weight += count; sum.hp += row.hp * count; sum.damage += row.damage * count;
      if (!paysRating(row.reward.type)) { sum.rewardWeight += count; sum.reward += row.reward.amount * count; }
    }
    return Object.fromEntries(Object.entries(sums).map(([role, sum]) =>
      [role, { hp: sum.hp / sum.weight, damage: sum.damage / sum.weight, reward: sum.reward / sum.rewardWeight }])) as Record<string, Stats>;
  });
  const DAMAGE = 'regular:damage';
  const later = roles.slice(1);
  // Each role against the damage camp, averaged over maps 2-15.
  const ratio: Record<string, Stats> = {};
  for (const role of new Set(later.flatMap(map => Object.keys(map)))) {
    const maps = later.filter(map => map[role]);
    ratio[role] = { hp: geomean(maps.map(map => map[role].hp / map[DAMAGE].hp)), damage: geomean(maps.map(map => map[role].damage / map[DAMAGE].damage)),
      reward: geomean(maps.map(map => map[role].reward / map[DAMAGE].reward)) };
  }
  const bossRatio = geomean(later.map((map, index) => snapshots[index + 1].boss!.hp / map[DAMAGE].hp));
  const forest = roles[0][DAMAGE];
  const enemies: Record<string, Record<string, Stats>> = {};
  const bosses: Record<string, { hp: number; attacks: Record<string, number> }> = {};
  CAMPAIGN_MAPS.forEach((map, index) => {
    const camp = { hp: forest.hp * CURVE_STEPS.health ** index, damage: forest.damage * CURVE_STEPS.damage ** index,
      reward: forest.reward * CURVE_STEPS.reward ** index };
    enemies[map.id] = Object.fromEntries(Object.entries(snapshots[index].enemies).map(([kind, row]) => {
      if (kind === 'Spitter') return [kind, { hp: row.hp, damage: row.damage, reward: row.reward.amount }];
      // A role only the Forest has (its regen camp) keeps its own size against the Forest's damage camp.
      const role = roleOf(row), target = ratio[role] ?? { hp: row.hp / forest.hp, damage: row.damage / forest.damage, reward: row.reward.amount / forest.reward };
      return [kind, { hp: round(camp.hp * target.hp), damage: round(camp.damage * target.damage), reward: round(camp.reward * target.reward) }];
    }));
    const hit = camp.damage / roles[index][DAMAGE].damage;
    bosses[map.id] = { hp: round(camp.hp * bossRatio), attacks: Object.fromEntries(Object.entries(snapshots[index].boss!.attacks).map(([key, value]) => [key, round(value * hit)])) };
  });
  return `// Generated by scripts/build-smooth-curve.ts from revision ${SMOOTH_CURVE_SOURCE.revision} (${SMOOTH_CURVE_SOURCE.fixture}).
// Every campaign map's enemies and boss on CURVE_STEPS (shared/curve-steps.ts): final values, regen boost included.
// Speed and crit camps pay their rating curve instead of this reward (stat-rating.ts).
export const SMOOTH_ENEMIES: Readonly<Record<string, Readonly<Record<string, { hp: number; damage: number; reward: number }>>>> = ${JSON.stringify(enemies, null, 2)};
export const SMOOTH_BOSSES: Readonly<Record<string, { hp: number; attacks: Readonly<Record<string, number>> }>> = ${JSON.stringify(bosses, null, 2)};
`;
}
