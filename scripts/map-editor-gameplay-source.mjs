/**
 * Builds shared/map-editor-overrides.ts from shared/map-designs.json. The map
 * editor writes both files together; scripts/generated-balance-files.test.ts
 * regenerates this one from the JSON and fails if they disagree.
 */
export function generatedGameplaySource(document) {
  const overrides = Object.fromEntries(Object.entries(document.maps ?? {})
    .filter(([, design]) => design.gameplayEdited)
    .map(([id, design]) => {
      const station = stationPosition(design);
      return [id, {
        name: design.name,
        arrival: design.gameplay.arrival,
        boss: design.gameplay.boss,
        ...(design.gameplay.bootsPickup ? { bootsPickup: design.gameplay.bootsPickup } : {}),
        ...(station ? { station } : {}),
        portals: design.gameplay.portals,
      }];
    }));
  return `/**\n * Generated by the local WildStat Map Editor (scripts/map-editor-server.mjs,\n * npm run map:editor) from shared/map-designs.json.\n * Do not hand-edit this file; the editor validates and replaces it atomically.\n */\nexport type MapEditorGameplayOverride = {\n  name: string;\n  arrival: { x: number; y: number };\n  boss: { x: number; y: number };\n  bootsPickup?: { x: number; y: number };\n  station?: { x: number; y: number };\n  portals: {\n    x: number;\n    y: number;\n    width: number;\n    height: number;\n    depth: number;\n    destination: string;\n  }[];\n};\n\nexport const MAP_EDITOR_GAMEPLAY_OVERRIDES: Readonly<Record<string, MapEditorGameplayOverride>> = ${JSON.stringify(overrides, null, 2)};\n`;
}

export function stationPosition(map) {
  const station = map?.decor.find((item) => item.type === "station");
  return station ? { x: station.x, y: station.y } : null;
}
