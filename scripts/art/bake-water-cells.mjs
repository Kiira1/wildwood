/**
 * Writes src/game/runtime/soul/soul-water-cells.ts: which 32-pixel cells of the village's water and shore masks
 * hold any water or foam. The river's light (soul-water.ts) only works on those, and used to find them by reading
 * every pixel of both masks back on the main thread the first time the Town was drawn. Run after re-baking the masks.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import sharp from "sharp";

const root = resolve(import.meta.dirname, "../..");
const CELL = 32;
const read = name => sharp(resolve(root, "public/assets/wildstat/soul-dimension", name)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const [water, shore] = await Promise.all([read("village-water.webp"), read("village-shore.webp")]);
const { width, height } = water.info;
if (shore.info.width !== width || shore.info.height !== height) throw new Error("The shore mask is not the water mask's size.");
const columns = Math.ceil(width / CELL), rows = Math.ceil(height / CELL);
const bits = new Uint8Array(Math.ceil(columns * rows / 8));
for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
  const alpha = (y * width + x) * 4 + 3;
  if (!water.data[alpha] && !shore.data[alpha]) continue;
  const cell = Math.floor(y / CELL) * columns + Math.floor(x / CELL);
  bits[cell >> 3] |= 1 << (cell & 7);
}
writeFileSync(resolve(root, "src/game/runtime/soul/soul-water-cells.ts"), `// Generated by scripts/art/bake-water-cells.mjs from village-water.webp and village-shore.webp. Do not edit.
/** The masks' size, the cell size in mask pixels, and one bit per cell, row by row (base64): 1 where there is water or foam. */
export const SOUL_WATER_CELLS = Object.freeze({ width: ${width}, height: ${height}, cellPixels: ${CELL}, bits: "${Buffer.from(bits).toString("base64")}" });
`);
console.log(`${columns}x${rows} cells, ${bits.reduce((sum, byte) => sum + byte.toString(2).replaceAll("0", "").length, 0)} wet`);
